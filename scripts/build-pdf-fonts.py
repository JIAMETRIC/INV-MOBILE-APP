# Builds src/export/pdfFonts.ts: base64 WOFF2 @font-face rules for the invoice
# HTML (PDF and live preview). Inter Regular + Bold, subset to Latin + the
# rupee sign, for text; Bebas Neue, subset to digits and number punctuation,
# for the number columns and totals. The full TTFs are ~340 KB each; the
# subsets keep the HTML small enough to re-render on every keystroke in the
# Create invoice preview.
# Glyphs outside the subsets (e.g. Tamil party names) fall back per character
# to the next font in the template's font stack.
#
#   python -I scripts/build-pdf-fonts.py        (needs: pip install fonttools brotli)
#
# Re-run after upgrading either @expo-google-fonts package; commit the generated file.
import base64
import io
import pathlib
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
PKGS = ROOT / 'node_modules' / '@expo-google-fonts'
OUT = ROOT / 'src' / 'export' / 'pdfFonts.ts'

# Basic Latin, Latin-1, dashes, quotes, bullet, ellipsis, rupee, minus.
TEXT_UNICODES = (
    list(range(0x20, 0x7F)) + list(range(0xA0, 0x100))
    + [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x20B9, 0x2212]
)
# Digits and what appears around them in amounts, quantities and dates.
NUMBER_UNICODES = [ord(c) for c in ' 0123456789.,-+%/:()'] + [0x20B9, 0x2212, 0xD7]

# (CSS family, weight, file under node_modules/@expo-google-fonts, unicodes)
FACES = [
    ('Inter', 400, 'inter/400Regular/Inter_400Regular.ttf', TEXT_UNICODES),
    ('Inter', 700, 'inter/700Bold/Inter_700Bold.ttf', TEXT_UNICODES),
    ('Bebas Neue', 400, 'bebas-neue/400Regular/BebasNeue_400Regular.ttf', NUMBER_UNICODES),
]


def woff2_base64(src: pathlib.Path, unicodes: list[int]) -> str:
    font = TTFont(src)
    opts = subset.Options()
    opts.flavor = 'woff2'
    opts.layout_features = ['kern', 'liga', 'calt', 'tnum', 'lnum']
    opts.name_IDs = ['*']
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=unicodes)
    sub.subset(font)
    buf = io.BytesIO()
    font.flavor = 'woff2'
    font.save(buf)
    return base64.b64encode(buf.getvalue()).decode('ascii')


def main() -> int:
    rules = []
    for family, weight, rel, unicodes in FACES:
        src = PKGS / rel
        if not src.exists():
            print(f'missing {src}; run npm install first', file=sys.stderr)
            return 1
        b64 = woff2_base64(src, unicodes)
        print(f'{rel}: {len(b64) * 3 // 4 // 1024} KB woff2 subset')
        rules.append(
            f"@font-face {{ font-family: '{family}'; font-weight: {weight}; font-style: normal; "
            f"src: url(data:font/woff2;base64,{b64}) format('woff2'); }}"
        )
    body = '\n'.join(f'  {r!r},' for r in rules)
    OUT.write_text(
        '// GENERATED by scripts/build-pdf-fonts.py. Do not edit by hand.\n'
        '// Inter 400/700 (Latin + rupee) and Bebas Neue 400 (digits), both SIL Open Font License 1.1.\n'
        f'export const PDF_FONT_CSS = [\n{body}\n].join(\'\\n\');\n',
        encoding='utf-8',
    )
    print(f'wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KB)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
